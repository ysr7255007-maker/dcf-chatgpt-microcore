#!/usr/bin/env node
/**
 * G2 Companion — Node SEA (Single Executable Application) build script
 *
 * Zero npm RUNTIME dependencies. Build-time tools:
 *   - node --experimental-sea-config (built-in)
 *   - postject via `npx --yes postject` (one-off build tool, recorded in evidence)
 *   - macOS codesign (system tool)
 *
 * Pipeline:
 *   1. Bundle seed/companion/*.js into one CommonJS file using a hand-written
 *      module-factory wrapper (no esbuild). Each source file is inserted
 *      verbatim inside its own function scope, so top-level `const fs = ...`
 *      declarations never collide and no fragile regex stripping is needed.
 *      Relative requires ('./types' etc.) resolve through a local registry;
 *      everything else falls through to the real require (built-ins only,
 *      which satisfies the SEA constraint that only built-ins are requirable).
 *   2. schema.sql is embedded as globalThis.__DCF_EMBEDDED_SCHEMA__ (JSON-escaped);
 *      db.js prefers it over reading schema.sql from disk.
 *   3. Generate SEA blob: node --experimental-sea-config
 *   4. Copy the running node binary to dist/dcf-companion, strip signature,
 *      inject blob with postject (NODE_SEA_BLOB + official fuse), re-sign ad-hoc.
 *
 * Artifacts (dist/ is gitignored):
 *   dist/dcf-companion              self-contained executable (final product)
 *   dist/companion-sea/bundle.js    intermediate bundle (also runnable via node)
 *   dist/companion-sea/sea-prep.blob, sea-config.json
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const SEED = path.join(ROOT, 'seed', 'companion');
const OUT_DIR = path.join(ROOT, 'dist', 'companion-sea');
const BINARY = path.join(ROOT, 'dist', 'dcf-companion');

const MODULES = ['ulid', 'types', 'doctor', 'db', 'events']; // dependency order
const FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';

function run(cmd, opts = {}) {
    console.log(`$ ${cmd}`);
    return execSync(cmd, { stdio: 'inherit', cwd: ROOT, ...opts });
}

function readSource(name) {
    return fs.readFileSync(path.join(SEED, `${name}.js`), 'utf8').replace(/^#!.*\n/, '');
}

console.log('G2 Companion SEA build');
console.log(`Node: ${process.version} (${process.platform}/${process.arch})\n`);

fs.mkdirSync(OUT_DIR, { recursive: true });

// ---------------------------------------------------------------------------
// Step 1: bundle
// ---------------------------------------------------------------------------
console.log('[1/4] Bundling seed/companion into single entry...');

const schema = fs.readFileSync(path.join(SEED, 'schema.sql'), 'utf8');

let bundle = `#!/usr/bin/env node
'use strict';
// G2 Companion — single-file bundle for Node SEA
// Generated by scripts/build-companion-sea.js — DO NOT EDIT
// Sources: seed/companion/{${MODULES.join(',')},index}.js + schema.sql (embedded)

const __nodeRequire = require;

// Embedded schema: db.js prefers this over reading schema.sql from disk,
// so the packaged binary never depends on the source directory.
globalThis.__DCF_EMBEDDED_SCHEMA__ = ${JSON.stringify(schema)};

const __registry = Object.create(null);
function __require(id) {
    const key = String(id).replace(/^\\.\\//, '').replace(/\\.js$/, '');
    if (key in __registry) return __registry[key];
    return __nodeRequire(id); // built-in modules only (SEA-safe)
}
`;

for (const name of MODULES) {
    bundle += `
// === seed/companion/${name}.js ===
__registry['${name}'] = (function () {
    const module = { exports: {} };
    (function (module, exports, require) {
${readSource(name)}
    })(module, module.exports, __require);
    return module.exports;
})();
`;
    console.log(`  + ${name}.js`);
}

// Entry: index.js runs main() only when require.main === module, so give the
// entry wrapper a require whose .main points at its own module object.
bundle += `
// === seed/companion/index.js (entry) ===
const __entryModule = { exports: {} };
const __entryRequire = function (id) { return __require(id); };
__entryRequire.main = __entryModule;
(function (module, exports, require) {
${readSource('index')}
})(__entryModule, __entryModule.exports, __entryRequire);
`;

const BUNDLE_PATH = path.join(OUT_DIR, 'bundle.js');
fs.writeFileSync(BUNDLE_PATH, bundle);
fs.chmodSync(BUNDLE_PATH, 0o755);

// Syntax gate before going further
run(`node --check "${BUNDLE_PATH}"`);
console.log(`  ✓ bundle: ${BUNDLE_PATH}\n`);

// ---------------------------------------------------------------------------
// Step 2: SEA blob
// ---------------------------------------------------------------------------
console.log('[2/4] Generating SEA preparation blob...');

const SEA_CONFIG = path.join(OUT_DIR, 'sea-config.json');
const SEA_BLOB = path.join(OUT_DIR, 'sea-prep.blob');
fs.writeFileSync(SEA_CONFIG, JSON.stringify({
    main: BUNDLE_PATH,
    output: SEA_BLOB,
    disableExperimentalSEAWarning: true
}, null, 2));

run(`node --experimental-sea-config "${SEA_CONFIG}"`);
console.log('  ✓ blob generated\n');

// ---------------------------------------------------------------------------
// Step 3: copy node binary + inject blob
// ---------------------------------------------------------------------------
console.log('[3/4] Injecting blob into node binary copy...');

fs.copyFileSync(process.execPath, BINARY);
fs.chmodSync(BINARY, 0o755);

if (process.platform === 'darwin') {
    // postject requires the signature to be removed first on macOS
    run(`codesign --remove-signature "${BINARY}"`);
}

// postject is a BUILD-TIME tool only (documented in evidence doc); prefer a
// local install if present, otherwise a one-off npx execution. A workspace
// npm cache is used because the user-level ~/.npm cache can contain
// root-owned files (observed EPERM on this machine).
const NPM_CACHE = path.join(ROOT, '.tmp-npm-cache');
const postjectArgs = `"${BINARY}" NODE_SEA_BLOB "${SEA_BLOB}" --sentinel-fuse ${FUSE}` +
    (process.platform === 'darwin' ? ' --macho-segment-name NODE_SEA' : '');
try {
    run(`npx --yes postject ${postjectArgs}`, {
        env: { ...process.env, npm_config_cache: NPM_CACHE }
    });
} catch (error) {
    console.error('\n✗ postject injection failed:', error.message);
    console.error('SEA binary could not be produced. The runnable fallback remains:');
    console.error(`  node ${BUNDLE_PATH}`);
    process.exit(1);
}

if (process.platform === 'darwin') {
    run(`codesign --sign - "${BINARY}"`);
}
console.log('  ✓ injected + re-signed\n');

// ---------------------------------------------------------------------------
// Step 4: sanity check
// ---------------------------------------------------------------------------
console.log('[4/4] Sanity check (--help via the standalone binary)...');
run(`"${BINARY}" --help`);

console.log('\n✓ Build complete');
console.log(`  Executable: ${BINARY}`);
console.log(`  Bundle:     ${BUNDLE_PATH} (fallback: node bundle.js)`);
